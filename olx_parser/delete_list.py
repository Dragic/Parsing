def delete_duplicates(ad_ids, batch_size=2):
    """
    Видаляє дублікати оголошень, залишаючи тільки запис з найвищим id для кожного ad_id.

    Args:
        ad_ids: список ad_id для яких потрібно видалити дублікати
        batch_size: розмір партії для обробки
    """
    total_deleted = 0

    # Розбиваємо список на партії
    for i in range(0, len(ad_ids), batch_size):
        batch = ad_ids[i:i + batch_size]
        print(f'start {i}')

        # Створюємо нову сесію для кожної партії
        session = DBSession()
        try:
            # Створюємо рядок з ad_id для підстановки в запит
            ad_ids_str = ','.join(str(ad_id) for ad_id in batch)

            # Запит для видалення дублікатів
            delete_query = text(f"""
            DELETE o1
            FROM offers o1
            JOIN offers o2 ON o1.ad_id = o2.ad_id
            WHERE o1.ad_id IN ({ad_ids_str})
            AND o1.id < o2.id
            AND o1.source = 'olx'
            AND o2.source = 'olx'
            """)

            # Виконуємо запит
            result = session.execute(delete_query)
            deleted_count = result.rowcount
            total_deleted += deleted_count

            # Зберігаємо зміни
            session.commit()

            print(f"Партія {i // batch_size + 1}: видалено {deleted_count} дублікатів")

        except Exception as e:
            session.rollback()
            print(f"Помилка при видаленні дублікатів в партії {i // batch_size + 1}: {e}")
        finally:
            session.close()

    print(f"Всього видалено {total_deleted} дублікатів")


# Альтернативний підхід через підзапит
def delete_duplicates_alt(ad_ids, batch_size=1000):
    """
    Альтернативний спосіб видалення дублікатів, залишаючи запис з найвищим id.
    """
    total_deleted = 0

    for i in range(0, len(ad_ids), batch_size):
        print(f'start {i}')
        batch = ad_ids[i:i + batch_size]

        session = DBSession()
        try:
            ad_ids_str = ','.join(str(ad_id) for ad_id in batch)

            # Альтернативний запит, який залишає запис з найвищим id
            delete_query = text(f"""
            DELETE FROM offers 
            WHERE source = 'olx'
            AND ad_id IN ({ad_ids_str})
            AND id NOT IN (
                SELECT max_id FROM (
                    SELECT MAX(id) as max_id
                    FROM offers
                    WHERE source = 'olx'
                    AND ad_id IN ({ad_ids_str})
                    GROUP BY ad_id
                ) as max_ids
            )
            """)

            result = session.execute(delete_query)
            deleted_count = result.rowcount
            total_deleted += deleted_count

            session.commit()

            print(f"Партія {i // batch_size + 1}: видалено {deleted_count} дублікатів")

        except Exception as e:
            session.rollback()
            print(f"Помилка при видаленні дублікатів в партії {i // batch_size + 1}: {e}")
        finally:
            session.close()

    print(f"Всього видалено {total_deleted} дублікатів")


def delete_duplicates_one_by_one(ad_ids):
    """
    Видаляє дублікати оголошень для кожного ad_id окремо,
    залишаючи тільки запис з найвищим id.

    Args:
        ad_ids: список ad_id для яких потрібно видалити дублікати
    """
    total_deleted = 0
    processed = 0

    start_time = time.time()

    for ad_id in ad_ids:
        session = DBSession()
        try:
            # Запит для видалення дублікатів для одного ad_id
            delete_query = text("""
            DELETE o1
            FROM offers o1
            JOIN offers o2 ON o1.ad_id = o2.ad_id
            WHERE o1.ad_id = :ad_id
            AND o1.id < o2.id
            AND o1.source = 'olx'
            AND o2.source = 'olx'
            """)

            # Виконуємо запит з параметром
            result = session.execute(delete_query, {"ad_id": ad_id})
            deleted_count = result.rowcount
            total_deleted += deleted_count

            # Зберігаємо зміни
            session.commit()

            processed += 1

            # Виводимо прогрес кожні 10 оброблених ad_id або для останнього
            if processed % 10 == 0 or processed == len(ad_ids):
                elapsed_time = time.time() - start_time
                avg_time = elapsed_time / processed
                estimated_remaining = avg_time * (len(ad_ids) - processed)

                print(f"Оброблено {processed}/{len(ad_ids)} ad_id. "
                      f"Видалено дублікатів: {total_deleted}. "
                      f"Минуло часу: {elapsed_time:.2f} с. "
                      f"Приблизно залишилось: {estimated_remaining:.2f} с.")

        except Exception as e:
            session.rollback()
            print(f"Помилка при видаленні дублікатів для ad_id {ad_id}: {e}")
        finally:
            session.close()

    print(f"Загалом оброблено {processed} ad_id. Всього видалено {total_deleted} дублікатів.")




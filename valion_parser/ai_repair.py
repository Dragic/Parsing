async def has_repair(text: str) -> bool:
    """
    Повертає True, якщо в тексті є ознаки виконаного ремонту.
    """
    try:
        """
            Логіка:
            1. Якщо в тексті немає слова "ремонт" -> False.
            2. Якщо є фраза "без ремонту" -> False.
            3. Беремо 30 символів до і 30 після слова "ремонт".
            4. Передаємо цей фрагмент в AI.
        """

        lower_text = text.lower()

        if "ремонт" not in lower_text:
            return False

        if "без ремонт" in lower_text or 'під ремонт' in lower_text:
            return False

        match = CONTEXT_RE.search(text)

        if not match:
            return False

        context = match.group(0).strip()

        response = await client.responses.create(
            model=MODEL,
            input=PROMPT_TEMPLATE.format(text=context),
        )

        result = response.output_text.strip().lower()

        return result == "true"
    except Exception as ex:
        logg.warning(f'Error during execute has_repair text: {text}. EX: {ex}')
        return False



